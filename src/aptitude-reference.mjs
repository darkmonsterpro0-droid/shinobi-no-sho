const portal='https://narutod8.weebly.com/';
export function aptitudeReference(key,book,fallback=''){
 const entry=aptitudeEntry(key,book);
 const detail=entry?.benefits||NOTES[canonical(key)]||String(fallback).trim()||'Consulte o efeito na fonte indicada.';
 return {detail,brief:detail.split(/(?<=\.)\s+/)[0],entry};
}
export function aptitudeRuleDetails(key,book,esc,fallback=''){
 const {detail,entry}=aptitudeReference(key,book,fallback);
 const source=entry?`${SOURCES[entry.book]??entry.book} · p. ${entry.page}`:'';
 const restrictions=entry?.restrictions?.filter(Boolean)??[];
 return `<details class="sns-aptitude-rule"><summary>Detalhes da regra</summary><p>${esc(detail)}</p>${entry?.requirements?`<p><strong>Pré-requisitos</strong> ${esc(entry.requirements)}</p>`:''}${restrictions.length?`<ul>${restrictions.map(text=>`<li>${esc(text)}</li>`).join('')}</ul>`:''}${source?`<p><small>${esc(source)} · resumo para consulta</small> · <a href="${links[entry.book]??portal}" target="_blank" rel="noopener">Ver fonte no Projeto D8</a></p>`:''}</details>`;
}
